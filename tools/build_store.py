import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from catalogue import COLLECTIONS, BOOKS, FREE, BUNDLES
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
books = [dict(slug=s, collection=c, title=t, audience=a, price=p, wave=w, inside=i) for s,c,t,a,p,w,i in BOOKS]
data = dict(collections=[dict(id=i,name=n) for i,n in COLLECTIONS], books=books,
            free=dict(slug=FREE[0], title=FREE[1], subtitle=FREE[2]),
            bundles=[dict(slug=s,title=t,subtitle=d,price=p,items=it) for s,t,d,p,it in BUNDLES])
open(os.path.join(root,'assets/js/catalogue.js'),'w').write('/* generated by tools/build_store.py from tools/catalogue.py */\nwindow.CATALOGUE = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
def q(x): return "'" + str(x).replace("'", "''") + "'"
rows = [f"({q(b['slug'])},{q(b['title'])},{q(b['collection'])},{b['price']*100},{b['wave']},false,null)" for b in books]
rows += [f"({q(s)},{q(t)},'bundle',{p*100},0,true,array[{','.join(q(x) for x in it)}]::text[])" for s,t,d,p,it in BUNDLES]
rows.append(f"({q(FREE[0])},{q(FREE[1])},'free',0,0,false,null)")
sql = "insert into public.products (slug,title,collection,price_kobo,wave,is_bundle,bundle_items) values\n" + ",\n".join(rows) + "\non conflict (slug) do update set title=excluded.title, collection=excluded.collection, price_kobo=excluded.price_kobo, wave=excluded.wave, is_bundle=excluded.is_bundle, bundle_items=excluded.bundle_items;\n"
open(os.path.join(root,'tools/products_seed.sql'),'w').write(sql)
print(len(books),'books', len(BUNDLES),'bundles')
